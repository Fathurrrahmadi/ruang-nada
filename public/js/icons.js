function replaceIcons() {
  document.querySelectorAll(".icon").forEach(function (element) {
    // lewati kalau sudah diganti
    if (element.firstElementChild) return;

    const paths = iconPaths[element.textContent.trim()];
    if (paths) {
      let shapes = "";
      paths.forEach(function (d) {
        shapes += '<path d="' + d + '"/>';
      });
      element.innerHTML = '<svg viewBox="0 0 24 24" aria-hidden="true">' + shapes + "</svg>";
    }
  });
}

// ganti ikon yang sudah ada di halaman
document.addEventListener("DOMContentLoaded", replaceIcons);

